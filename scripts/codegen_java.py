#!/usr/bin/env python3
"""Generate the Java contract enums from packages/contracts (OM-02, §8 §9).

Deterministic: fixed header, no timestamp, enum order = source order, the package dir is replaced
wholesale. Committed under libs/contracts-java/src/generated/java; tests/kit/test_om_02_contracts.py
regenerates and diffs, so stale enums fail CI. Records are hand-written (schema-parity tests guard them).

usage: codegen_java.py [--contracts DIR] [--out DIR] [--check]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "packages" / "contracts"
OUT = ROOT / "libs" / "contracts-java" / "src" / "generated" / "java"
PACKAGE = "com.secondline.contracts.generated"
HEADER = "// GENERATED by `make codegen-java` from packages/contracts (OM-02). Do not edit."


def comment(text: str) -> str:
    return text.replace("*/", "*&#47;")


def java_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def plain_enum(name: str, source: str, values: list[str]) -> str:
    body = ",\n".join(f"    {v}" for v in values)
    return (f"{HEADER}\npackage {PACKAGE};\n\n/** Values of {source}. */\npublic enum {name} {{\n{body}\n}}\n")


def http_status(e: dict) -> str:
    status = e["http_status"]
    if status is None:
        return "OptionalInt.empty()"
    if not isinstance(status, int) or isinstance(status, bool):
        raise SystemExit(f"errors.json {e['code']}: http_status must be an integer or null")
    return f"OptionalInt.of({status})"


def error_code(errors: list[dict]) -> str:
    consts = ",\n".join(
        f"    /** {comment(e['summary'])} */\n"
        f"    {e['code']}({http_status(e)}, {str(e['retryable']).lower()}, {str(e['grader_only']).lower()})"
        for e in errors)
    return f"""{HEADER}
package {PACKAGE};

import java.util.Arrays;
import java.util.List;
import java.util.OptionalInt;

/** Typed error codes from errors.json (§8). Runtime services pick from {{@link #runtimeValues()}}. */
public enum ErrorCode {{
{consts};

    private static final List<ErrorCode> RUNTIME = Arrays.stream(values()).filter(c -> !c.graderOnly).toList();

    private final OptionalInt httpStatus;
    private final boolean retryable;
    private final boolean graderOnly;

    ErrorCode(OptionalInt httpStatus, boolean retryable, boolean graderOnly) {{
        this.httpStatus = httpStatus;
        this.retryable = retryable;
        this.graderOnly = graderOnly;
    }}

    /** Empty for grader-only codes, which never travel over HTTP. */
    public OptionalInt httpStatus() {{
        return httpStatus;
    }}

    public boolean retryable() {{
        return retryable;
    }}

    /** Only the grader may return this code (e.g. ORACLE_MISMATCH); runtime services never do. */
    public boolean graderOnly() {{
        return graderOnly;
    }}

    /** Every code a runtime service may return: all codes except the grader-only ones. */
    public static List<ErrorCode> runtimeValues() {{
        return RUNTIME;
    }}
}}
"""


def render(contracts: Path) -> dict[str, str]:
    def load(rel: str) -> dict:
        return json.loads((contracts / rel).read_text(encoding="utf-8"))

    action = load("actions/proposed_action.schema.json")
    return {
        "ErrorCode.java": error_code(load("errors.json")["errors"]),
        "ReasonCode.java": plain_enum("ReasonCode", "common.schema.json#/$defs/reason_code",
                                      load("common.schema.json")["$defs"]["reason_code"]["enum"]),
        "ActionType.java": plain_enum("ActionType", "actions/proposed_action.schema.json type",
                                      action["properties"]["type"]["enum"]),
        "Decision.java": plain_enum("Decision", "receipts/decision_receipt.schema.json decision",
                                    load("receipts/decision_receipt.schema.json")["properties"]["decision"]["enum"]),
    }


def write(files: dict[str, str], out: Path) -> None:
    pkg = out / PACKAGE.replace(".", "/")
    if pkg.exists():
        shutil.rmtree(pkg)
    pkg.mkdir(parents=True)
    for name in sorted(files):
        (pkg / name).write_bytes(files[name].encode("utf-8"))


def stale(files: dict[str, str], out: Path) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        write(files, Path(tmp))
        fresh = {p.relative_to(tmp).as_posix(): p.read_bytes() for p in Path(tmp).rglob("*") if p.is_file()}
    have = {p.relative_to(out).as_posix(): p.read_bytes() for p in out.rglob("*") if p.is_file()} if out.exists() else {}
    return sorted(k for k in fresh.keys() | have.keys() if fresh.get(k) != have.get(k))


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--contracts", type=Path, default=CONTRACTS)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh run; write nothing")
    args = ap.parse_args(argv)
    files = render(args.contracts)
    if args.check:
        diff = stale(files, args.out)
        for rel in diff:
            print(f"stale: {rel} (run `make codegen-java`)")
        return 1 if diff else 0
    write(files, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
