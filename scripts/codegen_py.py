#!/usr/bin/env python3
"""Generate the sl_contracts pydantic models from packages/contracts JSON Schemas (KG-01, §19, NFR-06).

Deterministic: sorted inputs, no timestamp, fixed header, the output dir is replaced wholesale.
CI runs `make codegen-py && git diff --exit-code packages/contracts/py`, so stale models fail the build.

usage: codegen_py.py [--schemas DIR] [--out DIR]
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "packages" / "contracts"
OUT = SCHEMAS / "py" / "src" / "sl_contracts" / "_generated"
HEADER = "# GENERATED by `make codegen-py` from packages/contracts (KG-01). Do not edit."
GENERATOR_ARGS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-standard-collections", "--use-union-operator", "--use-schema-description",
    "--field-constraints", "--disable-timestamp",
    "--custom-file-header", HEADER, "--custom-file-header-mode", "replace",
    "--formatters", "builtin",
]


def schema_files(root: Path) -> list[Path]:
    # Only *.schema.json: errors.json, openapi/, examples/ and the generated py/ tree are not model sources.
    return sorted(p for p in root.rglob("*.schema.json") if "py" not in p.relative_to(root).parts)


def generate(schemas: Path, out: Path) -> None:
    files = schema_files(schemas)
    with tempfile.TemporaryDirectory() as tmp:
        staged, built = Path(tmp) / "in", Path(tmp) / "out"
        built.mkdir()
        for f in files:
            dest = staged / f.relative_to(schemas).with_name(f.name.removesuffix(".schema.json") + ".json")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f, dest)
        if files:
            r = subprocess.run([sys.executable, "-m", "datamodel_code_generator", "--input", str(staged),
                                "--output", str(built), *GENERATOR_ARGS], capture_output=True, text=True)
            if r.returncode != 0:
                raise SystemExit(f"codegen_py: datamodel-codegen failed:\n{r.stderr.strip()}")
        for d in [built, *(p for p in built.rglob("*") if p.is_dir())]:
            init = d / "__init__.py"
            if not init.exists() or not init.read_text().strip():
                init.write_text(HEADER + "\n")
        if out.exists():
            shutil.rmtree(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(built, out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--schemas", type=Path, default=SCHEMAS)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    generate(a.schemas.resolve(), a.out.resolve())
    print(f"codegen_py: {len(schema_files(a.schemas.resolve()))} schema(s) -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
